#!/usr/bin/env node
/* Builds js/alarms/<FCLT>.js — the offline FANUC alarm-code dictionary the
 * Robot tab's error history expands into — from linuxsand.info.
 *
 *   node tools/fetch-alarms.js [--only SRVO,INTP] [--rate 8] [--force]
 *
 * The source site is a SQLite lookup behind two open JSON endpoints:
 *   /fanuc/fclt-api/           -> every facility prefix, one "NAME id" per line
 *   /fanuc/code-api/SRVO-063   -> {"alarmInfoExists":true,"detail":"...Cause:...Remedy:..."}
 * Codes are strictly FCLT-NNN, so the only way to enumerate them is to sweep
 * 000-999 per facility. There is no early exit on a run of misses: SRVO has
 * hits up to 461 with wide gaps, and stopping early would silently truncate.
 *
 * That is ~92,000 requests against one small donation-funded droplet, so the
 * default rate is a deliberately polite 8/s (~3 hours). Each facility is
 * written atomically when it completes and skipped on a re-run, so a dropped
 * connection costs one facility rather than the whole sweep.
 *
 * The data is reproduced for internal reference with the site owner's
 * permission (granted by email, October 2026). Do not republish it.
 *
 * The output is committed so browser-only mode (file://) has it too.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const http = require('http');

const HOST = 'linuxsand.info';
const ROOT = path.join(__dirname, '..');
const OUTDIR = path.join(ROOT, 'js', 'alarms');

/* ---- args ---- */
const argv = process.argv.slice(2);
function arg(name, dflt) {
  const i = argv.indexOf('--' + name);
  return i === -1 ? dflt : argv[i + 1];
}
const onlyRaw = arg('only', '');
const ONLY = onlyRaw ? String(onlyRaw).split(',').map((s) => s.trim().toUpperCase()).filter(Boolean) : null;
const RATE = Math.max(1, Number(arg('rate', 8)) || 8);
const FORCE = argv.includes('--force');
const LIST = argv.includes('--list');
const CONC = Math.min(4, RATE);

/* ---- throttled GET ---- */
let nextSlot = 0;
const slotMs = 1000 / RATE;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function slot() {
  const now = Date.now();
  const at = Math.max(now, nextSlot);
  nextSlot = at + slotMs;
  if (at > now) await sleep(at - now);
}

function once(pathname) {
  return new Promise((resolve, reject) => {
    const req = http.get({
      host: HOST,
      path: pathname,
      headers: { 'User-Agent': 'FanucStudio/alarm-dictionary (local reference copy, by permission)' }
    }, (res) => {
      let body = '';
      res.setEncoding('utf8');
      res.on('data', (c) => { body += c; });
      res.on('end', () => resolve({ status: res.statusCode, body: body }));
    });
    req.setTimeout(15000, () => req.destroy(new Error('timeout')));
    req.on('error', reject);
  });
}

/* A 404 is a definitive "no such code", not a failure — only network faults
 * and 5xx are retried. */
async function get(pathname) {
  let last;
  for (let attempt = 0; attempt < 3; attempt++) {
    await slot();
    try {
      const r = await once(pathname);
      if (r.status < 500) return r;
      last = new Error('HTTP ' + r.status);
    } catch (e) {
      last = e;
    }
    await sleep(500 * Math.pow(3, attempt));
  }
  throw last;
}

/* ---- facilities ---- */
async function facilities() {
  const r = await get('/fanuc/fclt-api/');
  if (r.status !== 200) throw new Error('facility list: HTTP ' + r.status);
  const out = [];
  r.body.split(/\r?\n/).forEach((line) => {
    const m = line.match(/^\s*(\S+)\s+(\d+)\s*$/);   // "LECO  109" — note the double space
    if (m) out.push(m[1].toUpperCase());
  });
  if (!out.length) throw new Error('facility list came back empty');
  return out.sort();
}

/* ---- one facility ---- */
async function sweep(fclt) {
  const codes = {};
  const nums = [];
  for (let i = 0; i < 1000; i++) nums.push(String(i).padStart(3, '0'));
  let done = 0, failed = 0;

  async function worker() {
    for (;;) {
      const n = nums.shift();
      if (n === undefined) return;
      try {
        const r = await get('/fanuc/code-api/' + fclt + '-' + n + '?type=json');
        if (r.status === 200) {
          const j = JSON.parse(r.body);
          if (j.alarmInfoExists && j.detail) codes[n] = j.detail;
        }
      } catch (e) {
        failed++;
      }
      if (++done % 250 === 0) process.stdout.write('    ' + fclt + ' ' + done + '/1000\r');
    }
  }

  await Promise.all(Array.from({ length: CONC }, worker));
  return { codes: codes, failed: failed };
}

function write(fclt, codes) {
  const keys = Object.keys(codes).sort();
  const body = keys.map((k) => '    ' + JSON.stringify(k) + ': ' + JSON.stringify(codes[k])).join(',\n');
  const src =
    '/* FANUC ' + fclt + ' alarm codes — generated by tools/fetch-alarms.js,\n' +
    ' * DO NOT EDIT; re-run the tool instead. ' + keys.length + ' codes, ' + new Date().toISOString().slice(0, 10) + '.\n' +
    ' * Source: http://linuxsand.info/fanuc/ — internal reference copy, by permission. */\n' +
    '(function (global) {\n' +
    '  var data = {\n' + body + '\n  };\n' +
    "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n" +
    '  if (global.FanucAlarms) global.FanucAlarms._put(' + JSON.stringify(fclt) + ', data);\n' +
    "})(typeof window !== 'undefined' ? window : globalThis);\n";
  const out = path.join(OUTDIR, fclt + '.js');
  const tmp = out + '.tmp';
  fs.writeFileSync(tmp, src);
  fs.renameSync(tmp, out);          // atomic: a killed run never leaves a half file
  return keys.length;
}

/* ---- main ---- */
(async function main() {
  fs.mkdirSync(OUTDIR, { recursive: true });
  const all = await facilities();
  console.log(all.length + ' facilities on the site');
  if (LIST) { console.log(all.join(' ')); return; }

  /* js/alarms.js carries the list as a literal so a lookup never spends a
   * request discovering that a prefix is not a facility. Warn if it drifts. */
  try {
    const known = require(path.join(ROOT, 'js', 'alarms.js')).facilities;
    const missing = all.filter((f) => known.indexOf(f) === -1);
    const extra = known.filter((f) => all.indexOf(f) === -1);
    if (missing.length || extra.length) {
      console.log('NOTE: the js/alarms.js facility list is out of date.');
      if (missing.length) console.log('  site has, loader lacks: ' + missing.join(' '));
      if (extra.length) console.log('  loader has, site lacks: ' + extra.join(' '));
    }
  } catch (e) { /* loader not written yet */ }

  const want = ONLY ? all.filter((f) => ONLY.indexOf(f) !== -1) : all;
  if (ONLY) {
    const unknown = ONLY.filter((f) => all.indexOf(f) === -1);
    if (unknown.length) console.log('not facilities, skipped: ' + unknown.join(' '));
  }

  let total = 0, fetched = 0, skipped = 0;
  const started = Date.now();
  for (let i = 0; i < want.length; i++) {
    const f = want[i];
    const out = path.join(OUTDIR, f + '.js');
    const tag = '[' + (i + 1) + '/' + want.length + '] ' + f;
    if (!FORCE && fs.existsSync(out)) {
      const n = Object.keys(require(out)).length;
      total += n; skipped++;
      console.log(tag + ' — have it, ' + n + ' codes');
      continue;
    }
    const r = await sweep(f);
    const n = write(f, r.codes);
    total += n; fetched++;
    console.log(tag + ' — ' + n + ' codes' +
      (r.failed ? ', ' + r.failed + ' requests failed' : '') +
      '  (' + ((Date.now() - started) / 60000).toFixed(1) + ' min elapsed)');
  }
  console.log('\n' + total + ' codes across ' + want.length + ' facilities — ' +
    fetched + ' fetched, ' + skipped + ' already present.');
})().catch((e) => { console.error('fetch-alarms failed: ' + e.message); process.exit(1); });
